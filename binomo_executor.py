def _signal_stream_url() -> str:
    base = config.get_public_base_url()
    token = config.get_admin_access_token()
    if not token:
        raise RuntimeError(
            "ADMIN_ACCESS_TOKEN is not set — the local executor needs it to "
            "read /api/signal-stream from the cloud instance."
        )
    return f"{base}/api/signal-stream?admin_token={token}"


_STREAM_RECONNECT_BASE_SECONDS = 5
_STREAM_RECONNECT_MAX_SECONDS = 60
# The cloud side publishes an "_ping" SSE event every 20s (app.py's
# sse_ping loop) specifically so a live connection always has *something*
# arriving. A read timeout comfortably above that (45s - over 2 missed
# pings) means a connection that silently stalls (TCP session dropped by
# a NAT/router without a clean FIN) gets detected and reconnected, instead
# of requests.get(..., timeout=(10, None)) blocking client.events()
# forever with no read timeout to ever trigger the except/reconnect path
# below. Defense-in-depth, not a confirmed-bug fix: a 2026-08-18 restart
# that LOOKED like exactly this (8+ minutes of total silence) turned out,
# on a live py-spy stack dump, to be a healthy process the whole time -
# the main loop was cycling normally on signal_queue.get(timeout=2.0) and
# the SSE thread was blocked on a live socket read() waiting for the next
# event, both textbook-idle, not stuck. The silence was refresh_watchlist_
# by_payout's own no-changes branch logging at DEBUG (invisible at the
# default INFO level) rather than anything wrong with this stream.
_STREAM_READ_TIMEOUT_SECONDS = 45


def _stream_signals(out_queue: "queue.Queue[dict]", stop_event: threading.Event) -> None:
    """SSE connections drop regularly (ChunkedEncodingError, idle proxy
    timeouts, etc.) - that's normal, not a bug, as long as this reconnects.
    Exponential backoff (capped) so a sustained cloud-side outage doesn't
    hammer it every few seconds; backoff resets once an event actually
    arrives, so a brief blip doesn't leave a stale long delay in place.
    Treats the generator ending WITHOUT an exception the same as a
    disconnect and still backs off before retrying - some sseclient-py
    versions can end the loop silently on a dropped connection instead of
    raising, and a stream that's supposed to be infinite ending "cleanly"
    is itself a disconnect, not a normal completion."""
    import sseclient

    url = _signal_stream_url()
    backoff = _STREAM_RECONNECT_BASE_SECONDS

    while not stop_event.is_set():
        connected_at = time.monotonic()
        response = None
        try:
            response = requests.get(url, stream=True, timeout=(10, _STREAM_READ_TIMEOUT_SECONDS))
            client = sseclient.SSEClient(response)
            for event in client.events():
                if stop_event.is_set():
                    break
                if not event.data:
                    continue
                try:
                    payload = json.loads(event.data)
                except ValueError:
                    continue
                if payload.get("_ping"):
                    continue
                out_queue.put(payload)
                backoff = _STREAM_RECONNECT_BASE_SECONDS
        except Exception:
            logger.warning(
                "Binomo executor: signal stream disconnected after %.0fs",
                time.monotonic() - connected_at, exc_info=True,
            )
        finally:
            if response is not None:
                try:
                    response.close()
                except Exception:
                    pass

        if stop_event.is_set():
            break

        logger.info("Binomo executor: signal stream reconnecting in %ss", backoff)
        if stop_event.wait(backoff):
            break
        backoff = min(backoff * 2, _STREAM_RECONNECT_MAX_SECONDS)


