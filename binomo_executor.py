def _stake_weight_for_pair(pair: str) -> float:
    """Multiplier on BINOMO_STAKE_PERCENT for this pair, chosen by ITS OWN
    trailing 30-day Binomo-style win rate (see config.py's
    BINOMO_STAKE_WEIGHT_* for the tiers/thresholds and, importantly, why
    this is not martingale). A pair with fewer than
    BINOMO_STAKE_WEIGHT_MIN_TRADES resolved signals gets
    BINOMO_STAKE_WEIGHT_DEFAULT - not full size, since there isn't enough
    history to trust yet, but not zero either."""
    stats = db.get_pair_signal_outcome_stats(pair, days=30)
    resolved = stats.get("resolved") or 0
    win_rate = stats.get("win_rate")

    if resolved < config.BINOMO_STAKE_WEIGHT_MIN_TRADES or win_rate is None:
        return config.BINOMO_STAKE_WEIGHT_DEFAULT
    if win_rate >= config.BINOMO_STAKE_WEIGHT_TIER_HIGH_WINRATE:
        return config.BINOMO_STAKE_WEIGHT_TIER_HIGH
    if win_rate >= config.BINOMO_STAKE_WEIGHT_TIER_MID_WINRATE:
        return config.BINOMO_STAKE_WEIGHT_TIER_MID
    if win_rate >= config.BINOMO_STAKE_WEIGHT_TIER_BREAKEVEN_WINRATE:
        return config.BINOMO_STAKE_WEIGHT_TIER_BREAKEVEN
    return config.BINOMO_STAKE_WEIGHT_TIER_LOW


def _handle_signal(page, asset_map: dict, signal: dict) -> None:
    if not is_active():
        return

    verdict = str(signal.get("verdict_text") or "").upper()
    if verdict not in ("BUY", "SELL"):
        return

    pair = str(signal.get("pair") or "").upper()
    entry = asset_map.get(pair)
    asset_name = entry and _resolve_binomo_asset_name(entry)
    if not asset_name:
        logger.debug("Binomo executor: %s not tradable on Binomo right now, skipping", pair)
        return

    weight = _stake_weight_for_pair(pair)
    if weight <= 0:
        logger.info(
            "Binomo executor: %s stake weight is 0 (30d Binomo-style win rate below breakeven) - skipping trade",
            pair,
        )
        return

    balance = get_account_balance(page)
    if not balance or balance <= 0:
        logger.warning("Binomo executor: could not read balance, skipping %s", pair)
        return

    block_reason = _check_risk_limits(balance)
    if block_reason:
        logger.info("Binomo executor: blocked %s (%s)", pair, block_reason)
        return

    direction = "up" if verdict == "BUY" else "down"
    expiry_seconds = signal_tracking.compute_horizon_seconds(signal.get("timeframe"))
    amount = round(balance * (config.BINOMO_STAKE_PERCENT / 100.0) * weight, 2)
    if int(round(amount)) < 1:
        logger.warning(
            "Binomo executor: computed stake for %s rounds to 0 (balance=%.2f weight=%.2f) - skipping trade",
            pair, balance, weight,
        )
        return

    trade_id = db.create_binomo_trade(
        asset=asset_name,
        pair=pair,
        direction=direction,
        amount=amount,
        expiry_seconds=expiry_seconds,
        account_mode=config.BINOMO_ACCOUNT_MODE,
    )
    if not trade_id:
        logger.error("Binomo executor: could not log pending trade for %s, aborting placement", pair)
        return

    logger.info(
        "BINOMO: placing #%s %s %s amount=%.2f (weight=%.2f) expiry=%ss (mode=%s)",
        trade_id, asset_name, direction, amount, weight, expiry_seconds, config.BINOMO_ACCOUNT_MODE,
    )
    result = place_binary_trade(page, asset_name, direction, amount, expiry_seconds)

    if not result["success"]:
        db.mark_binomo_trade_error(trade_id, result["error"] or "unknown error")
        notify_admin(f"❌ Binomo #{trade_id} {asset_name} {direction}: {result['error']}")
        return

    # BUG found live 2026-08-12: entry_ts (stamped by create_binomo_trade,
    # above, BEFORE place_binary_trade's real click sequence even starts)
    # was the wrong reference point for read_trade_result's entered_after
    # comparison whenever placement itself took a while - see
    # db.update_binomo_trade_entry_ts's docstring for the live incident
    # this caused (not one real trade resolved successfully all day).
    # Corrected here, right after placement is confirmed to have actually
    # succeeded, to whatever placement really took - however long that was.
    db.update_binomo_trade_entry_ts(trade_id, datetime.now(timezone.utc).replace(tzinfo=None))

    # BUG found live 2026-08-13: the expiry stepper's per-click step size
    # isn't fixed/predictable - see db.update_binomo_trade_expiry_seconds's
    # docstring. actual_expiry_seconds is what place_binary_trade really
    # achieved; persisted here so due_at math and reporting reflect it
    # rather than the aspirational request.
    actual_expiry_seconds = result["actual_expiry_seconds"] or expiry_seconds
    db.update_binomo_trade_expiry_seconds(trade_id, actual_expiry_seconds)

    notify_admin(
        f"📥 Binomo #{trade_id} {asset_name} {direction.upper()}\n"
        f"Сума: {amount:.2f} · Експірація: {actual_expiry_seconds}с"
        + (f" (запитано {expiry_seconds}с)" if actual_expiry_seconds != expiry_seconds else "")
        + f" · Режим: {config.BINOMO_ACCOUNT_MODE}"
    )


def _resolve_due_trades(page) -> None:
    """Resolves every currently-due pending trade in ONE open/close of the
    trade-history panel, not one open/close per trade.

    BUG found live 2026-08-13: the user watched the live browser and
    caught this directly - the "Угоди" panel was visibly opening and
    closing 4 times within a couple of seconds. Root cause: this used to
    call read_trade_result (open panel, scan, close panel) separately for
    every due trade in the loop below, so N pending trades due in the same
    pass meant N full open/close cycles back to back. Wasteful, and
    actively risky given the same day's other findings: every open/close
    is one more chance to hit the promo-modal or close-transition-timing
    edge cases already fixed once today (see _open_trade_history_panel /
    _close_trade_history_panel) - doing it 4x as often as necessary just
    multiplies the exposure. Now opens the panel once, selects the FTT
    sub-tab once, scans every due trade against that same open panel via
    _read_settled_result, then closes once - and skips opening it at all
    when nothing is actually due.

    ALSO gated by _resolve_check_interval (2026-08-13, user decision): the
    "skip if nothing due" guard above only ever prevented opening the
    panel - it never stopped the DB query + due-check itself from running
    on every single main-loop pass, ~every 2s, which in practice was
    happening constantly since there's almost always at least one pending
    trade somewhere in its window. That's still a fixed, regular polling
    rate even with nothing to show for it. Now the whole function is a
    no-op unless the randomized interval says it's due - see
    _RandomizedInterval's docstring for why random, not fixed."""
    if not _resolve_check_interval.is_due():
        return
    _resolve_check_interval.mark_fired()

    now = datetime.now(timezone.utc).replace(tzinfo=None)

    due_trades = []
    for trade in db.get_pending_binomo_trades(config.BINOMO_ACCOUNT_MODE):
        entry_ts = trade["entry_ts"]
        if not isinstance(entry_ts, datetime):
            continue
        due_at = entry_ts.timestamp() + trade["expiry_seconds"]
        if now.timestamp() < due_at:
            continue
        due_trades.append(trade)

    if not due_trades:
        return

    if not _open_trade_history_panel(page):
        return

    try:
        _select_trade_history_standard_tab(page)

        for trade in due_trades:
            outcome = _read_settled_result(page, trade["asset"], trade["entry_ts"], trade["expiry_seconds"])
            if outcome["result"] == "unknown":
                continue  # try again next pass; don't guess

            if db.resolve_binomo_trade(trade["id"], result=outcome["result"], payout_amount=outcome["payout_amount"]):
                payout = outcome["payout_amount"]
                logger.info(
                    "BINOMO: #%s %s %s -> %s (payout=%s)",
                    trade["id"], trade["asset"], trade["direction"], outcome["result"], payout,
                )
                notify_admin(
                    f"📤 Binomo #{trade['id']} {trade['asset']} {trade['direction'].upper()} "
                    f"→ {outcome['result'].upper()}"
                    + (f" ({payout:+.2f})" if isinstance(payout, (int, float)) else "")
                )
    finally:
        _close_trade_history_panel(page)


def run(*, headless: bool = None) -> None:
    from playwright.sync_api import sync_playwright

    if not config.BINOMO_EXECUTOR_ENABLED:
        logger.warning("BINOMO_EXECUTOR_ENABLED=false — exiting immediately. Set it in your local .env to run.")
        return

    asset_map = load_asset_map()
    if not asset_map:
        logger.error("Binomo asset map is empty — nothing to trade. Check %s", config.BINOMO_ASSET_MAP_PATH)
        return

    signal_queue: "queue.Queue[dict]" = queue.Queue()
    stop_event = threading.Event()
    stream_thread = threading.Thread(
        target=_stream_signals, args=(signal_queue, stop_event), name="binomo-signal-stream", daemon=True
    )
    stream_thread.start()

    with sync_playwright() as p:
        browser, context, page = _launch_session(p, headless=config.BINOMO_HEADLESS if headless is None else headless)

        if not _is_logged_in(page):
            notify_admin(
                "🛑 Binomo executor: сесія недійсна/протермінована. "
                "Запусти `python binomo_executor.py --login` вручну на ноуті."
            )
            logger.critical("Binomo executor: not logged in (stale storage_state?). Exiting.")
            browser.close()
            stop_event.set()
            return

        logger.info("Binomo executor started (mode=%s, enabled=%s)", config.BINOMO_ACCOUNT_MODE, config.BINOMO_EXECUTOR_ENABLED)

        try:
            while True:
                if not _session_still_valid(page):
                    break

                try:
                    _maybe_refresh_watchlist(page, asset_map)

                    try:
                        signal = signal_queue.get(timeout=2.0)
                        _handle_signal(page, asset_map, signal)
                    except queue.Empty:
                        pass

                    _resolve_due_trades(page)
                except Exception:
                    _log_unexpected_loop_error("run")
                    time.sleep(5)
        except KeyboardInterrupt:
            logger.info("Binomo executor stopping (KeyboardInterrupt).")
        finally:
            stop_event.set()
            browser.close()


# ----------------------------------------------------------------------
# --correlation-check: does the cTrader feed's direction actually match
# Binomo's own feed for the same asset/horizon? Places NO trades and
# ignores risk limits/kill switch entirely — pure observation, logged to
# a CSV. Deliberately independent of Part 1's SignalOutcome table (which
# only ever tracks cTrader-side movement) per the task's own instruction
# not to conflate the two.
# ----------------------------------------------------------------------


def _fetch_ctrader_price(pair: str) -> Optional[float]:
    base = config.get_public_base_url()
    token = config.get_admin_access_token()
    if not token:
        logger.error("Correlation-check: ADMIN_ACCESS_TOKEN not set, cannot fetch cTrader price")
        return None

    try:
        response = requests.get(
            f"{base}/api/live_price", params={"pairs": pair, "admin_token": token}, timeout=10
        )
        response.raise_for_status()
        data = response.json()
        entry = (data.get("prices") or {}).get(pair)
        return entry.get("mid") if entry else None
    except Exception:
        logger.exception("Correlation-check: failed to fetch cTrader price for %s", pair)
        return None


def _read_binomo_price(page, asset_name: str, *, timeout_seconds: float = 8.0) -> Optional[float]:
    """Reads from the WebSocket price cache (see _install_price_feed_listener),
    not the DOM — Binomo's price is canvas-rendered with no accessible DOM/
    SVG text anywhere (confirmed live 2026-08-09 and re-confirmed 2026-08-10),
    but ticks arrive continuously over wss://as.binomo.com/. Polls briefly
    for a FRESH tick rather than trusting whatever's cached, since
    _select_asset() clears the cache on every switch and the new asset's
    subscription needs a moment to start streaming.

    Waits for the feed to SETTLE on one RIC before trusting a tick: right
    after an asset switch, ticks for the previously-viewed asset can still
    arrive, and recording one of those as the new asset's price would
    silently corrupt exactly the comparison correlation-check exists to
    produce. Also cross-checks against the RIC previously observed for this
    asset name, so a wrong-asset price is refused rather than logged. A
    missing price is harmless here (logs as 'unknown'); a wrong one is not."""
    deadline = time.monotonic() + timeout_seconds
    stable_ric = None
    stable_since = None
    last_seen_ric = None

    while time.monotonic() < deadline:
        with _price_feed_lock:
            rate = _price_feed_state["rate"]
            received_at = _price_feed_state["received_at"]
            ric = _price_feed_state["ric"]

        now = time.monotonic()
        fresh = (
            rate is not None
            and received_at is not None
            and now - received_at <= _PRICE_FEED_STALE_SECONDS
        )

        if fresh:
            last_seen_ric = ric
            if ric != stable_ric:
                stable_ric, stable_since = ric, now
            elif now - stable_since >= _PRICE_FEED_SETTLE_SECONDS:
                known_ric = _asset_ric_map.get(asset_name)
                if known_ric is not None and known_ric != ric:
                    logger.error(
                        "Binomo executor: price feed is on RIC %r but %r was previously %r — "
                        "refusing this tick rather than recording another asset's price",
                        ric, asset_name, known_ric,
                    )
                    return None
                if known_ric is None and ric is not None:
                    _asset_ric_map[asset_name] = ric
                    logger.info("Binomo executor: learned RIC for %s -> %s", asset_name, ric)
                return rate

        page.wait_for_timeout(200)

    logger.warning(
        "Binomo executor: no settled price tick for %s within %ss (last_ric=%s) — "
        "feed silent or still switching assets",
        asset_name, timeout_seconds, last_seen_ric,
    )
    return None


_resource_last_logged_at: Optional[float] = None


def _log_resource_usage(pending: list) -> None:
    """Logs this process's memory once an hour during long correlation-check
    runs. Deliberately measurement, not mitigation: whether a multi-day run
    actually leaks (the Binomo SPA is never reloaded, and Playwright holds
    an object per WebSocket) is unknown, and guessing at a fix for an
    unmeasured problem would be worse than collecting the numbers first.
    psutil is optional - absent, this logs the queue depth only rather than
    becoming a hard dependency of the executor."""
    global _resource_last_logged_at

    now = time.monotonic()
    if _resource_last_logged_at is not None and now - _resource_last_logged_at < _RESOURCE_LOG_INTERVAL_SECONDS:
        return
    _resource_last_logged_at = now

    try:
        import psutil

        rss_mb = psutil.Process().memory_info().rss / (1024 * 1024)
        logger.info(
            "Correlation-check resources: RSS=%.1f MB, pending_entries=%d",
            rss_mb, len(pending),
        )
    except ImportError:
        logger.info(
            "Correlation-check resources: pending_entries=%d (psutil not installed — "
            "`pip install psutil` to also log memory)", len(pending),
        )
    except Exception:
        logger.debug("Could not sample resource usage", exc_info=True)


def _log_unexpected_loop_error(loop_name: str) -> None:
    """Called from the per-iteration except Exception in run()/
    run_correlation_check() - see the crash this guards against in
    _safe_click's docstring. Logs with a traceback and pages the admin once
    (alert_key cooldown) rather than letting an unexpected error kill a
    multi-day unattended run over what should be a single skipped signal."""
    logger.exception("Binomo executor: unexpected error in %s loop iteration — continuing.", loop_name)
    notify_admin(
        f"⚠️ Binomo executor: неочікувана помилка в циклі {loop_name} (див. логи локально). "
        "Процес НЕ зупинено, продовжує роботу.",
        alert_key=f"binomo_loop_error_{loop_name}",
    )


def refresh_watchlist_by_payout(page, asset_map: dict) -> None:
    """Keeps the scanner watchlist limited to pairs Binomo is CURRENTLY
    quoting under a real (non-OTC) name at config.BINOMO_MIN_PAYOUT_PERCENT
    or more. Binomo's '(OTC)' listings are its own synthetic/generated price
    series, not a real market feed - POLICY (user decision, 2026-08-11):
    never trade or track a pair under that name, so a pair only reachable
    via otc_name never qualifies here, full stop (this used to also check
    otc_name; that fallback is gone - see _resolve_binomo_asset_name's
    docstring for the same policy applied to trade placement). Concrete
    effect: crypto (only ever listed OTC on Binomo) never qualifies, and a
    forex pair with a real binomo_name drops out for as long as Binomo
    happens to be showing it under OTC (confirmed live 2026-08-10/11 for
    USD/CAD and GBP/USD on ordinary weekday nights) - it comes back on its
    own once Binomo returns it to the real listing, no manual fix needed.

    Only ever manages pairs already present in asset_map (the cTrader x
    Binomo intersection) - it adds/removes exactly those, leaving any other
    watchlist entries the user added by hand untouched.

    Reuses the caller's already-open `page` rather than opening its own
    session: a second concurrent Binomo session was confirmed live
    2026-08-10 to trigger an overlay that blocked clicks in the FIRST
    session (see _safe_click's docstring for the crash that caused) — this
    must only ever run from inside run()'s/run_correlation_check()'s own
    loop, on their own page."""
    user_id = config.get_chat_id()
    if not user_id:
        logger.warning("refresh_watchlist_by_payout: no chat id configured, skipping.")
        return

    live_assets = get_available_binomo_assets(page)
    if not live_assets:
        logger.warning("refresh_watchlist_by_payout: got no assets back from Binomo, skipping this round.")
        return

    payout_by_name = {item["name"]: item["payout_percent"] for item in live_assets}
    current_watchlist = set(db.get_watchlist(user_id))

    added, removed = [], []
    for pair_key, entry in asset_map.items():
        binomo_name = entry.get("binomo_name")
        payout = payout_by_name.get(binomo_name) if binomo_name else None
        qualifies = payout is not None and payout >= config.BINOMO_MIN_PAYOUT_PERCENT
        already_present = pair_key in current_watchlist

        if qualifies and not already_present:
            if db.add_to_watchlist(user_id, pair_key):
                added.append(f"{pair_key} ({payout:.0f}%)")
        elif not qualifies and already_present:
            if db.remove_from_watchlist(user_id, pair_key):
                removed.append(f"{pair_key} ({payout:.0f}%)" if payout is not None else f"{pair_key} (n/a)")

    if added or removed:
        logger.info(
            "Watchlist payout refresh (>=%.0f%%): +%d %s, -%d %s",
            config.BINOMO_MIN_PAYOUT_PERCENT, len(added), added, len(removed), removed,
        )
    else:
        logger.debug("Watchlist payout refresh: no changes (%d pairs tracked).", len(asset_map))


def _maybe_refresh_watchlist(page, asset_map: dict) -> None:
    """Gated by _watchlist_refresh_interval (a randomized delay, not a
    fixed one) - see that class's docstring."""
    if not _watchlist_refresh_interval.is_due():
        return
    _watchlist_refresh_interval.mark_fired()
    refresh_watchlist_by_payout(page, asset_map)


def _classify_or_unknown(entry: Optional[float], exit_: Optional[float]) -> str:
    if not isinstance(entry, (int, float)) or not isinstance(exit_, (int, float)):
        return "unknown"
    return signal_tracking._classify_move(entry, exit_)


def _append_correlation_log(row: dict) -> None:
    CORRELATION_LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    is_new = not CORRELATION_LOG_PATH.exists()
    with open(CORRELATION_LOG_PATH, "a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=CORRELATION_LOG_FIELDS)
        if is_new:
            writer.writeheader()
        writer.writerow(row)


def _start_correlation_entry(page, asset_map: dict, signal: dict, pending: list, lock: threading.Lock) -> None:
    verdict = str(signal.get("verdict_text") or "").upper()
    if verdict not in ("BUY", "SELL"):
        return

    pair = str(signal.get("pair") or "").upper()
    entry = asset_map.get(pair)
    asset_name = entry and _resolve_binomo_asset_name(entry)
    if not asset_name:
        return

    ctrader_entry_price = signal.get("price")
    if not isinstance(ctrader_entry_price, (int, float)):
        return

    select_error = _select_asset(page, asset_name)
    if select_error:
        logger.warning("Correlation-check: could not select %s (%s), skipping this signal", asset_name, select_error)
        return

    binomo_entry_price = _read_binomo_price(page, asset_name)
    horizon_seconds = signal_tracking.compute_horizon_seconds(signal.get("timeframe"))

    record = {
        "pair": pair,
        "binomo_asset": asset_name,
        "verdict": verdict,
        "horizon_seconds": horizon_seconds,
        "ctrader_entry_price": ctrader_entry_price,
        "binomo_entry_price": binomo_entry_price,
        "due_at": time.time() + horizon_seconds,
    }
    with lock:
        pending.append(record)

    logger.info(
        "Correlation-check: tracking %s %s ctrader_entry=%s binomo_entry=%s (horizon=%ss)",
        pair, verdict, ctrader_entry_price, binomo_entry_price, horizon_seconds,
    )


def _resolve_due_correlation_entries(page, pending: list, lock: threading.Lock) -> None:
    now = time.time()
    with lock:
        due = [r for r in pending if r["due_at"] <= now]
        for r in due:
            pending.remove(r)

    for record in due:
        ctrader_exit_price = _fetch_ctrader_price(record["pair"])

        binomo_exit_price = None
        select_error = _select_asset(page, record["binomo_asset"])
        if select_error:
            logger.warning(
                "Correlation-check: could not re-select %s for exit price (%s)",
                record["binomo_asset"], select_error,
            )
        else:
            binomo_exit_price = _read_binomo_price(page, record["binomo_asset"])

        ctrader_direction = _classify_or_unknown(record["ctrader_entry_price"], ctrader_exit_price)
        binomo_direction = _classify_or_unknown(record["binomo_entry_price"], binomo_exit_price)
        match = ctrader_direction == binomo_direction and ctrader_direction != "unknown"

        _append_correlation_log(
            {
                "logged_at": datetime.now(timezone.utc).isoformat(),
                "pair": record["pair"],
                "binomo_asset": record["binomo_asset"],
                "verdict": record["verdict"],
                "horizon_seconds": record["horizon_seconds"],
                "ctrader_entry_price": record["ctrader_entry_price"],
                "ctrader_exit_price": ctrader_exit_price,
                "ctrader_direction": ctrader_direction,
                "binomo_entry_price": record["binomo_entry_price"],
                "binomo_exit_price": binomo_exit_price,
                "binomo_direction": binomo_direction,
                "match": match,
            }
        )
        logger.info(
            "Correlation-check RESULT: %s ctrader=%s binomo=%s match=%s",
            record["pair"], ctrader_direction, binomo_direction, match,
        )


def run_correlation_check(*, headless: bool = None) -> None:
    from playwright.sync_api import sync_playwright

    asset_map = load_asset_map()
    if not asset_map:
        logger.error("Binomo asset map is empty — nothing to check. See %s", config.BINOMO_ASSET_MAP_PATH)
        return

    pending: list = []
    lock = threading.Lock()

    signal_queue: "queue.Queue[dict]" = queue.Queue()
    stop_event = threading.Event()
    stream_thread = threading.Thread(
        target=_stream_signals, args=(signal_queue, stop_event), name="binomo-correlation-stream", daemon=True
    )
    stream_thread.start()

    with sync_playwright() as p:
        browser, context, page = _launch_session(p, headless=config.BINOMO_HEADLESS if headless is None else headless)

        if not _is_logged_in(page):
            logger.critical("Correlation-check: not logged in. Run `python binomo_executor.py --login` first.")
            browser.close()
            stop_event.set()
            return

        logger.info(
            "Correlation-check started — NO trades will be placed, only price "
            "comparisons logged to %s. Leave this running for a few days before "
            "trusting these signals with real money.",
            CORRELATION_LOG_PATH,
        )

        try:
            while True:
                if not _session_still_valid(page):
                    break

                try:
                    _log_resource_usage(pending)
                    _maybe_refresh_watchlist(page, asset_map)

                    try:
                        signal = signal_queue.get(timeout=2.0)
                        _start_correlation_entry(page, asset_map, signal, pending, lock)
                    except queue.Empty:
                        pass

                    _resolve_due_correlation_entries(page, pending, lock)
                except Exception:
                    _log_unexpected_loop_error("correlation-check")
                    time.sleep(5)
        except KeyboardInterrupt:
            logger.info("Correlation-check stopping (KeyboardInterrupt).")
        finally:
            stop_event.set()
            browser.close()


def clear_kill_switch_cli() -> None:
    """Local, explicit alternative to Telegram's /binomo_on, added
    2026-08-13 because the owner didn't have Telegram at hand right when
    the kill switch tripped. Does exactly what binomo_on_command does in
    telegram_ui.py (db.set_binomo_runtime_enabled(True) +
    db.clear_binomo_kill_switch()) - same recovery action, different door.

    Deliberately a standalone CLI command that only runs when the owner
    types it themselves - never call this from anywhere in the run loop
    (_check_risk_limits, _resolve_due_trades, etc.). CLAUDE.md's kill-switch
    rule requires an explicit admin action to resume after
    MAX_CONSECUTIVE_LOSSES/MAX_DAILY_LOSS_PERCENT trips specifically so a
    losing streak can't silently keep going - automating this call from
    inside the executor would defeat that."""
    before = db.get_binomo_runtime_state()
    print(f"До: {before}")
    db.set_binomo_runtime_enabled(True)
    db.clear_binomo_kill_switch()
    after = db.get_binomo_runtime_state()
    print(f"Після: {after}")


