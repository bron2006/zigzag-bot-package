# Trade placement
# ----------------------------------------------------------------------


def place_binary_trade(page, asset: str, direction: str, amount: float, expiry_seconds: int) -> dict:
    """direction: 'up' | 'down'. Returns {"success": bool, "error": str|None}.
    Every real click on amount/direction is preceded by an audit screenshot,
    per the task's audit-trail requirement."""
    if direction not in ("up", "down"):
        return {"success": False, "error": f"invalid direction: {direction}"}

    search_input = _safe_find(page, SELECTORS["asset_search_input"], description="asset_search_input")
    if search_input is None:
        return {"success": False, "error": "asset_search_input not found"}
    search_input.fill(asset)

    asset_option = _safe_find(page, f"{SELECTORS['asset_option']}:has-text('{asset}')", description="asset_option")
    if asset_option is None:
        return {"success": False, "error": f"asset option not found for {asset!r}"}
    asset_option.click()

    expiry_dropdown = _safe_find(page, SELECTORS["expiry_selector"], description="expiry_selector")
    if expiry_dropdown is None:
        return {"success": False, "error": "expiry_selector not found"}
    expiry_dropdown.click()

    expiry_option = _safe_find(
        page, f"{SELECTORS['expiry_option']}:has-text('{expiry_seconds}')", description="expiry_option"
    )
    if expiry_option is None:
        return {"success": False, "error": f"expiry option not found for {expiry_seconds}s"}
    expiry_option.click()

    amount_input = _safe_find(page, SELECTORS["amount_input"], description="amount_input")
    if amount_input is None:
        return {"success": False, "error": "amount_input not found"}

    _screenshot(page, f"before_amount_{asset}_{direction}")
    amount_input.fill(f"{amount:.2f}")

    direction_selector = SELECTORS["up_button"] if direction == "up" else SELECTORS["down_button"]
    direction_button = _safe_find(page, direction_selector, description=f"{direction}_button")
    if direction_button is None:
        return {"success": False, "error": f"{direction}_button not found"}

    _screenshot(page, f"before_click_{asset}_{direction}")
    direction_button.click()

    confirmation = _safe_find(
        page, SELECTORS["trade_confirmation_toast"], description="trade_confirmation_toast", timeout_ms=5000
    )
    if confirmation is None:
        # Not necessarily a failure — some UIs skip a toast — but we can't
        # positively confirm the trade went through either. Log loudly.
        logger.warning("Binomo executor: no confirmation toast seen after clicking %s on %s", direction, asset)

    return {"success": True, "error": None}


def read_trade_result(page, asset: str, entered_after: datetime) -> dict:
    """Reads the most recent resolved trade for `asset` opened at/after
    `entered_after` from Binomo's trade history. Returns
    {"result": "win"|"loss"|"unknown", "payout_amount": float|None}."""
    history_tab = _safe_find(page, SELECTORS["trade_history_tab"], description="trade_history_tab")
    if history_tab is None:
        return {"result": "unknown", "payout_amount": None}
    history_tab.click()

    row = _safe_find(page, f"{SELECTORS['trade_history_row']}:has-text('{asset}')", description="trade_history_row")
    if row is None:
        return {"result": "unknown", "payout_amount": None}

    try:
        text = row.inner_text().lower()
        if "win" in text or "виграш" in text:
            outcome = "win"
        elif "loss" in text or "програш" in text:
            outcome = "loss"
        else:
            outcome = "unknown"

        digits = "".join(ch for ch in text if ch.isdigit() or ch in ".,-").strip()
        payout = float(digits.replace(",", "")) if digits else None
        return {"result": outcome, "payout_amount": payout}
    except Exception:
        logger.exception("Could not parse Binomo trade history row for %s", asset)
        return {"result": "unknown", "payout_amount": None}


# ----------------------------------------------------------------------
# Risk checks
# ----------------------------------------------------------------------


def _check_risk_limits(balance: float) -> Optional[str]:
    """Returns a reason string if a trade should be blocked, else None.
    Trips the kill switch itself when a hard limit (consecutive losses /
    daily loss) is breached."""
    trades_today = db.count_binomo_trades_today(config.BINOMO_ACCOUNT_MODE)
    if trades_today >= config.BINOMO_MAX_TRADES_PER_DAY:
        return f"MAX_TRADES_PER_DAY reached ({trades_today}/{config.BINOMO_MAX_TRADES_PER_DAY})"

    losses = db.get_consecutive_binomo_losses(config.BINOMO_ACCOUNT_MODE)
    if losses >= config.BINOMO_MAX_CONSECUTIVE_LOSSES:
        _trip_kill_switch(
            f"{losses} збитків поспіль (ліміт {config.BINOMO_MAX_CONSECUTIVE_LOSSES})"
        )
        return "MAX_CONSECUTIVE_LOSSES kill switch tripped"

    daily_pnl = db.get_daily_binomo_pnl(config.BINOMO_ACCOUNT_MODE)
    max_daily_loss = balance * (config.BINOMO_MAX_DAILY_LOSS_PERCENT / 100.0)
    if daily_pnl <= -max_daily_loss:
        _trip_kill_switch(
            f"Денний PnL {daily_pnl:.2f} перевищив ліміт -{max_daily_loss:.2f} "
            f"({config.BINOMO_MAX_DAILY_LOSS_PERCENT}% балансу)"
        )
        return "MAX_DAILY_LOSS_PERCENT kill switch tripped"

    return None


# ----------------------------------------------------------------------
# Signal stream (background thread — only ever pushes into a queue; all
# Playwright calls stay on the main thread, since a Page isn't safe to
# drive from multiple threads at once)
# ----------------------------------------------------------------------


def _signal_stream_url() -> str:
    base = config.get_public_base_url()
    token = config.get_admin_access_token()
    if not token:
        raise RuntimeError(
            "ADMIN_ACCESS_TOKEN is not set — the local executor needs it to "
            "read /api/signal-stream from the cloud instance."
        )
    return f"{base}/api/signal-stream?admin_token={token}"


def _stream_signals(out_queue: "queue.Queue[dict]", stop_event: threading.Event) -> None:
    import sseclient

    url = _signal_stream_url()
    while not stop_event.is_set():
        try:
            response = requests.get(url, stream=True, timeout=(10, None))
            client = sseclient.SSEClient(response)
            for event in client.events():
                if stop_event.is_set():
                    break
                if not event.data:
                    continue
                try:
                    payload = json.loads(event.data)
                except ValueError:
                    continue
                if payload.get("_ping"):
                    continue
                out_queue.put(payload)
        except Exception:
            logger.warning("Binomo executor: signal stream disconnected, retrying in 10s", exc_info=True)
            time.sleep(10)


# ----------------------------------------------------------------------
# Main loop
# ----------------------------------------------------------------------


def _handle_signal(page, asset_map: dict, signal: dict) -> None:
    if not is_active():
        return

    verdict = str(signal.get("verdict_text") or "").upper()
    if verdict not in ("BUY", "SELL"):
        return

    pair = str(signal.get("pair") or "").upper()
    entry = asset_map.get(pair)
    if not entry or not entry.get("binomo_name"):
        logger.debug("Binomo executor: %s not in asset map, skipping", pair)
        return

    balance = get_account_balance(page)
    if not balance or balance <= 0:
        logger.warning("Binomo executor: could not read balance, skipping %s", pair)
        return

    block_reason = _check_risk_limits(balance)
    if block_reason:
        logger.info("Binomo executor: blocked %s (%s)", pair, block_reason)
        return

    direction = "up" if verdict == "BUY" else "down"
    expiry_seconds = signal_tracking.compute_horizon_seconds(signal.get("timeframe"))
    amount = round(balance * (config.BINOMO_STAKE_PERCENT / 100.0), 2)
    asset_name = entry["binomo_name"]

    trade_id = db.create_binomo_trade(
        asset=asset_name,
        pair=pair,
        direction=direction,
        amount=amount,
        expiry_seconds=expiry_seconds,
        account_mode=config.BINOMO_ACCOUNT_MODE,
    )
    if not trade_id:
        logger.error("Binomo executor: could not log pending trade for %s, aborting placement", pair)
        return

    logger.info(
        "BINOMO: placing #%s %s %s amount=%.2f expiry=%ss (mode=%s)",
        trade_id, asset_name, direction, amount, expiry_seconds, config.BINOMO_ACCOUNT_MODE,
    )
    result = place_binary_trade(page, asset_name, direction, amount, expiry_seconds)

    if not result["success"]:
        db.mark_binomo_trade_error(trade_id, result["error"] or "unknown error")
        notify_admin(f"❌ Binomo #{trade_id} {asset_name} {direction}: {result['error']}")
        return

    notify_admin(
        f"📥 Binomo #{trade_id} {asset_name} {direction.upper()}\n"
        f"Сума: {amount:.2f} · Експірація: {expiry_seconds}с · Режим: {config.BINOMO_ACCOUNT_MODE}"
    )


def _resolve_due_trades(page) -> None:
    now = datetime.now(timezone.utc).replace(tzinfo=None)

    for trade in db.get_pending_binomo_trades(config.BINOMO_ACCOUNT_MODE):
        entry_ts = trade["entry_ts"]
        if not isinstance(entry_ts, datetime):
            continue
        due_at = entry_ts.timestamp() + trade["expiry_seconds"]
        if now.timestamp() < due_at:
            continue

        outcome = read_trade_result(page, trade["asset"], entry_ts)
        if outcome["result"] == "unknown":
            continue  # try again next pass; don't guess

        if db.resolve_binomo_trade(trade["id"], result=outcome["result"], payout_amount=outcome["payout_amount"]):
            payout = outcome["payout_amount"]
            logger.info(
                "BINOMO: #%s %s %s -> %s (payout=%s)",
                trade["id"], trade["asset"], trade["direction"], outcome["result"], payout,
            )
            notify_admin(
                f"📤 Binomo #{trade['id']} {trade['asset']} {trade['direction'].upper()} "
                f"→ {outcome['result'].upper()}"
                + (f" ({payout:+.2f})" if isinstance(payout, (int, float)) else "")
            )


def run(*, headless: bool = None) -> None:
    from playwright.sync_api import sync_playwright

    if not config.BINOMO_EXECUTOR_ENABLED:
        logger.warning("BINOMO_EXECUTOR_ENABLED=false — exiting immediately. Set it in your local .env to run.")
        return

    asset_map = load_asset_map()
    if not asset_map:
        logger.error("Binomo asset map is empty — nothing to trade. Check %s", config.BINOMO_ASSET_MAP_PATH)
        return

    signal_queue: "queue.Queue[dict]" = queue.Queue()
    stop_event = threading.Event()
    stream_thread = threading.Thread(
        target=_stream_signals, args=(signal_queue, stop_event), name="binomo-signal-stream", daemon=True
    )
    stream_thread.start()

    with sync_playwright() as p:
        browser, context, page = _launch_session(p, headless=config.BINOMO_HEADLESS if headless is None else headless)

        if not _is_logged_in(page):
            notify_admin(
                "🛑 Binomo executor: сесія недійсна/протермінована. "
                "Запусти `python binomo_executor.py --login` вручну на ноуті."
            )
            logger.critical("Binomo executor: not logged in (stale storage_state?). Exiting.")
            browser.close()
            stop_event.set()
            return

        logger.info("Binomo executor started (mode=%s, enabled=%s)", config.BINOMO_ACCOUNT_MODE, config.BINOMO_EXECUTOR_ENABLED)

        try:
            while True:
                try:
                    signal = signal_queue.get(timeout=2.0)
                    _handle_signal(page, asset_map, signal)
                except queue.Empty:
                    pass

                _resolve_due_trades(page)
        except KeyboardInterrupt:
            logger.info("Binomo executor stopping (KeyboardInterrupt).")
        finally:
            stop_event.set()
            browser.close()


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(name)s - %(levelname)s - %(message)s")

    parser = argparse.ArgumentParser(description="Binomo binary-option executor (local, Playwright-based).")
    parser.add_argument("--login", action="store_true", help="One-time/manual login helper; saves storage_state.json.")
    parser.add_argument("--run", action="store_true", help="Run the live executor loop.")
    parser.add_argument("--headless", action="store_true", help="Force headless mode for --run.")
    args = parser.parse_args()

    if args.login:
        login_and_save_session()
    elif args.run:
        run(headless=True if args.headless else None)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
