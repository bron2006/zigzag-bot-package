# Asset map
# ----------------------------------------------------------------------


def load_asset_map() -> dict[str, dict]:
    path = Path(config.BINOMO_ASSET_MAP_PATH)
    if not path.is_absolute():
        path = config.BASE_DIR / path

    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception:
        logger.exception("Could not load Binomo asset map from %s", path)
        return {}

    assets = data.get("assets") or {}
    if not data.get("_meta", {}).get("verified"):
        logger.warning(
            "Binomo asset map (%s) is marked unverified — trades will only be "
            "placed for pairs whose Binomo name has been manually confirmed. "
            "See _meta.how_to_verify in the file.",
            path,
        )
    return assets


