def is_active() -> bool:
    if not config.BINOMO_EXECUTOR_ENABLED:
        return False

    state = db.get_binomo_runtime_state()
    global _local_kill_switch_cache
    _local_kill_switch_cache = state["kill_switch_tripped"]
    return state["runtime_enabled"] and not state["kill_switch_tripped"]


def _trip_kill_switch(reason: str) -> None:
    if db.trip_binomo_kill_switch(reason):
        logger.critical("BINOMO KILL SWITCH: %s", reason)
        notify_admin(
            f"🛑 <b>BINOMO KILL SWITCH</b>\n{reason}\n"
            "Виконавця зупинено. Перевір рахунок вручну, тоді /binomo_on.",
            parse_mode="HTML",
        )


