def login_and_save_session() -> None:
    """One-time (or as-needed) login helper: opens a VISIBLE browser and, if
    BINOMO_EMAIL/BINOMO_PASSWORD are set, pre-fills the login form as a
    convenience — it never clicks submit and never touches a CAPTCHA/2FA
    field; you always complete and confirm the login yourself. Saves the
    session to BINOMO_STORAGE_STATE_PATH once you confirm you're in. Run
    with:
        python binomo_executor.py --login
    """
    from playwright.sync_api import sync_playwright

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=False)
        context = browser.new_context()
        page = context.new_page()
        page.goto(BINOMO_BASE_URL)

        if config.BINOMO_EMAIL and config.BINOMO_PASSWORD:
            try:
                page.wait_for_selector(SELECTORS["login_email_input"], timeout=_DEFAULT_FIND_TIMEOUT_MS)
                page.fill(SELECTORS["login_email_input"], config.BINOMO_EMAIL)
                page.fill(SELECTORS["login_password_input"], config.BINOMO_PASSWORD)
                print("Pre-filled email/password from .env — review, solve any CAPTCHA, then submit yourself.")
            except Exception:
                logger.warning(
                    "Could not pre-fill the login form (selector may need updating) — fill it in manually.",
                    exc_info=True,
                )

        print(
            "\nA browser window has opened. Log into your Binomo account "
            "yourself (solve any CAPTCHA/2FA yourself — this tool never "
            "attempts that, and never clicks the submit button for you). "
            "Once you're logged in and can see your balance, come back "
            "here and press Enter.\n"
        )
        input("Press Enter once logged in... ")

        state_path = _storage_state_path()
        state_path.parent.mkdir(parents=True, exist_ok=True)
        context.storage_state(path=str(state_path))
        print(f"Session saved to {state_path}. You can close the browser now.")
        browser.close()


def _install_price_feed_listener(page) -> None:
    """Taps Binomo's price WebSocket, caching the latest tick as
    {rate, ric, received_at}. Ticks look like
    {"data":[{"assets":[{"rate":...,"ric":"BTCUSD-OTC"}]}]} - the RIC is
    Binomo's internal asset id, which is what makes it possible to tell
    whose price a tick actually is (verified live: switching the chart
    between assets changes the incoming RIC accordingly)."""
    def _on_websocket(ws):
        if _PRICE_FEED_WS_HOST not in ws.url:
            return

        def _on_frame_received(payload):
            if not isinstance(payload, str):
                return
            try:
                msg = json.loads(payload)
            except ValueError:
                return
            for item in msg.get("data") or []:
                for asset in item.get("assets") or []:
                    rate = asset.get("rate")
                    if not isinstance(rate, (int, float)):
                        continue
                    with _price_feed_lock:
                        _price_feed_state["rate"] = float(rate)
                        _price_feed_state["ric"] = asset.get("ric")
                        _price_feed_state["received_at"] = time.monotonic()

        ws.on("framereceived", _on_frame_received)

    page.on("websocket", _on_websocket)


# Display name ("Bitcoin (OTC)") -> RIC ("BTCUSD-OTC"), learned at runtime.
# Binomo publishes no mapping and the two name spaces don't derive from each
# other ("Crypto IDX" is "Z-CRY/IDX"), so it's observed once per asset and
# then used to detect a tick belonging to the wrong asset.
_asset_ric_map: dict[str, str] = {}


def _clear_price_feed_cache() -> None:
    """Drops the cached tick so a price from the previously-viewed asset
    can't be read as the new one's. The learned name->RIC map is kept: it
    doesn't go stale on asset switches and is what lets _read_binomo_price
    verify the tick it eventually accepts."""
    with _price_feed_lock:
        _price_feed_state["rate"] = None
        _price_feed_state["ric"] = None
        _price_feed_state["received_at"] = None


def _launch_session(playwright, *, headless: bool):
    state_path = _storage_state_path()
    if not state_path.exists():
        raise RuntimeError(
            f"No saved Binomo session at {state_path}. Run "
            "`python binomo_executor.py --login` first."
        )

    browser = playwright.chromium.launch(headless=headless)
    context = browser.new_context(storage_state=str(state_path))
    page = context.new_page()
    _install_price_feed_listener(page)
    page.goto(BINOMO_TRADE_URL)
    return browser, context, page


