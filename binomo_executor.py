def _parse_hhmm(text: str) -> Optional[int]:
    try:
        h, m = text.strip().split(":")
        return int(h) * 60 + int(m)
    except Exception:
        return None


def _set_expiry_time(page, expiry_seconds: int) -> Optional[int]:
    """Binomo's expiry control (#qa_trading_dealTimeInput) is a readonly
    absolute clock-time field. An earlier version of this function (see git
    history) advanced it via the +/- stepper buttons — abandoned 2026-08-13
    after a live incident: the stepper's per-click step size turned out to
    be unpredictable/accelerating (confirmed live: consecutive clicks from
    the same baseline advanced the field by 2 minutes, then 1, with no
    discoverable pattern), so a request for 300s (5min) landed real trades
    anywhere from ~5 to ~30 minutes actual duration in production.

    REPLACED with the mechanism the user pointed out from their own manual
    trading experience (2026-08-13) and confirmed live here via read-only
    DOM inspection before writing this: clicking the time INPUT (not the
    stepper) opens a <vui-popover>, nested inside #qa_trading_dealTimeInput
    itself (confirmed: not portaled elsewhere in the DOM), listing exact
    selectable "HH:MM" options (div.option.analytics-time — confirmed live,
    9 options: 1-minute granularity for the next ~5 minutes, then a jump to
    :00/:15/:30/:45 marks further out). This selects the smallest option
    that reaches or exceeds the target directly, in one click, instead of
    guessing how many stepper clicks are needed. Also confirmed live:
    selecting an option does NOT auto-close the popover, but the popover
    staying open does not block clicks elsewhere on the page (checked via
    elementFromPoint at the amount input while the popover was still open)
    — so no explicit dismiss step is needed here; the next real click
    elsewhere in place_binary_trade's flow closes it as a side effect.

    Reads via a Locator (page.locator(...).input_value()), not a captured
    ElementHandle - same reasoning as _safe_click's 2026-08-12 rewrite: our
    own click can make Angular swap this very node, and a read on a stale
    handle can raise instead of returning the current value.

    Still returns the ACTUAL elapsed seconds reached, not the requested
    value - NOT a bool. The picker's granularity means the smallest
    available option can be > target when the target itself isn't one of
    the offered marks (e.g. a 20-minute request when only :15/:30 marks are
    listed). The caller persists this TRUE duration, not the requested one
    - see _handle_signal's use of db.update_binomo_trade_expiry_seconds.

    BUG found live 2026-08-13, same day as the picker rewrite above: the
    first version of this function read the field's displayed value BEFORE
    opening the picker and used that as the "elapsed 0" reference point for
    every option. Confirmed live that this reference is not reliable: at
    one live check the field read "20:51" and the popover's own first
    (soonest) option was "20:52" (i.e. baseline+1) - but at another live
    check moments later, the field read "21:00" and the popover's first
    option was ALSO "21:00" (i.e. baseline+0, not +1). Which one you get
    depends on exactly where "now" falls within the current minute at
    click time, which Binomo doesn't expose precisely enough to predict.
    In the baseline+0 case, the near-term 1-minute block (0,1,2,3,4) can
    never satisfy a 5-minute (300s) target - elapsed>=5 is never true in
    that block - so the old logic always jumped to the next :00/:15/:30/:45
    mark instead, which landed a real trade at ~18 minutes instead of 5.

    FIX: never read the field separately before opening the picker at all -
    that read is exactly the value that turned out to be unreliable. Use
    the popover's OWN first (soonest) option, read from the same snapshot
    used for selecting, as the reference point instead - internally
    consistent by construction, no separate read to go stale. That
    reference itself represents "about 1 minute from now" in the common
    case (as observed above), so the target is shifted down by 1 minute to
    compensate. This does not remove the small (<60s) uncertainty in what
    the reference instant precisely is - Binomo's own picker is
    minute-granularity, so this was never resolvable to the second - but it
    keeps that uncertainty under a minute instead of letting it compound
    into a jump to a random quarter-hour mark."""
    time_input_probe = _safe_find(page, SELECTORS["time_input"], description="time_input")
    if time_input_probe is None:
        return None
    time_input = page.locator(SELECTORS["time_input"])
    value_before_click = time_input.input_value()

    if not _safe_click(page, SELECTORS["time_input"], description="time_input"):
        return None

    if _safe_find(page, SELECTORS["time_picker_option"], description="time_picker_option") is None:
        return None

    try:
        option_elements = page.query_selector_all(SELECTORS["time_picker_option"])
    except Exception:
        logger.exception("Binomo executor: could not list expiry time picker options")
        return None

    options: list[tuple[str, int]] = []
    for el in option_elements:
        try:
            text = el.inner_text().strip()
        except Exception:
            continue
        minutes = _parse_hhmm(text)
        if minutes is not None:
            options.append((text, minutes))

    if not options:
        shot = _screenshot(page, "no_expiry_picker_options")
        logger.error(
            "Binomo executor: expiry time picker opened but no parseable options were found — "
            "not guessing further. Screenshot: %s", shot,
        )
        notify_admin(
            "⚠️ Binomo executor: пікер часу експірації відкрився, але жодної опції не вдалося "
            f"розпізнати. Потрібна ручна перевірка. Скріншот: {shot or 'не вдалося зберегти'}",
            alert_key="binomo_no_expiry_picker_options",
        )
        return None

    # options[0] is the popover's own soonest offer — used as the reference
    # instant instead of any separately-read field value (see docstring).
    _, anchor_minutes = options[0]
    target_relative = max(1, round(expiry_seconds / 60)) - 1

    best_text: Optional[str] = None
    best_elapsed: Optional[int] = None
    for text, minutes in options:
        elapsed = (minutes - anchor_minutes) % (24 * 60)
        if elapsed >= target_relative and (best_elapsed is None or elapsed < best_elapsed):
            best_elapsed = elapsed
            best_text = text

    # Unreachable in practice: options[0] itself always has elapsed 0, which
    # satisfies target_relative (always >= 0) - kept as a guard, not a guess.
    if best_text is None or best_elapsed is None:
        logger.error("Binomo executor: could not select an expiry picker option (target=%ss)", expiry_seconds)
        return None

    option_selector = f"{SELECTORS['time_picker_option']}:text-is('{best_text}')"
    if not _safe_click(page, option_selector, description="time_picker_option"):
        return None

    try:
        page.wait_for_function(
            "([sel, prev]) => document.querySelector(sel)?.value !== prev",
            arg=[SELECTORS["time_input"], value_before_click],
            timeout=2000,
        )
    except Exception:
        logger.debug(
            "Binomo executor: expiry field didn't visibly change after picking a time option", exc_info=True
        )

    elapsed_seconds = (best_elapsed + 1) * 60
    if elapsed_seconds != expiry_seconds:
        logger.info(
            "Binomo executor: expiry set via picker to the nearest available option - "
            "requested %ss, got %ss.", expiry_seconds, elapsed_seconds,
        )
    return elapsed_seconds


def _fill_amount(page, amount: float) -> bool:
    """A plain .fill() on this Angular currency-masked input was confirmed
    live to silently mangle the value (typed "40.00", field showed "₴40.4")
    instead of erroring. Switching to character-by-character typing
    surfaced a second finding: this field doesn't accept a decimal point at
    all — it silently drops "." and concatenates the remaining digits (typed
    "40.00" -> field showed "₴4000"), confirmed 2026-08-09 on this UAH demo
    account. Rounds to the nearest whole currency unit and types digits
    only, then reads the field back and refuses to proceed on any mismatch
    rather than trusting the input silently worked.

    Interacts via a Locator (page.locator(...)), not a captured
    ElementHandle - see _safe_click's 2026-08-12 rewrite docstring for the
    live bug (a click that reports success but never visibly lands) this
    avoids for every action here, not just the click."""
    amount_input_probe = _safe_find(page, SELECTORS["amount_input"], description="amount_input")
    if amount_input_probe is None:
        return False
    amount_input = page.locator(SELECTORS["amount_input"])

    target = int(round(amount))
    if not _safe_click(page, SELECTORS["amount_input"], description="amount_input"):
        return False
    amount_input.press("Control+A")
    amount_input.press("Backspace")
    amount_input.type(str(target))

    actual = _parse_numeric_text(amount_input.input_value())
    if actual is None or abs(actual - target) > 0.5:
        shot = _screenshot(page, "amount_mismatch")
        logger.error(
            "Binomo executor: amount field shows %r after typing %d (requested %.2f) — "
            "mismatch, not trusting it and aborting. Screenshot: %s",
            amount_input.input_value(), target, amount, shot,
        )
        notify_admin(
            f"⚠️ Binomo executor: поле суми показує {amount_input.input_value()!r} "
            f"замість {target} — угоду скасовано, потрібна ручна перевірка."
        )
        return False

    return True


def _dismiss_blocking_overlay(page) -> None:
    """Best-effort dismissal of whatever Angular overlay/dialog Binomo
    happens to be showing (confirmed live 2026-08-11/12: a "Стати
    VIP-трейдером" promo modal repeatedly intercepted the picker-open
    click - see _safe_click's docstring for the crash that class of
    failure caused before that guard existed). Rather than hunting down
    and hardcoding that one promo's close button - which only guesses at
    what the NEXT such popup will look like - this sends Escape, confirmed
    live to close this app's Angular overlays generically (verified
    2026-08-12 against the asset picker itself). A no-op when nothing is
    open, so it's cheap to call unconditionally before every picker
    interaction. Also cleans up the "search_input not found on the very
    next action" cascade failures seen after a blocked click - those look
    like the picker was left half-open by the interrupted attempt."""
    try:
        page.keyboard.press("Escape")
    except Exception:
        logger.debug("Binomo executor: overlay-dismiss Escape press failed", exc_info=True)


def _select_asset(page, asset: str) -> Optional[str]:
    """Opens the asset picker, searches, and clicks the exact-matching row
    (exact-match matters: the weekday name, e.g. "EUR/USD", is a text
    substring of the weekend one, "EUR/USD (OTC)"). Returns None on
    success, or an error string. Shared by place_binary_trade and the
    correlation-check price-reading flow - neither means anything until
    the chart is actually showing the requested asset. Clears the
    WebSocket price cache on success so a stale price from whatever was
    previously selected can never be mistaken for the new asset's."""
    _dismiss_blocking_overlay(page)
    picker_button_probe = _safe_find(page, SELECTORS["asset_picker_open_button"], description="asset_picker_open_button")
    if picker_button_probe is None:
        return "asset_picker_open_button not found"
    if not _safe_click(page, SELECTORS["asset_picker_open_button"], description="asset_picker_open_button"):
        return "could not click asset_picker_open_button"

    search_input = _safe_find(page, SELECTORS["asset_search_input"], description="asset_search_input")
    if search_input is None:
        return "asset_search_input not found"
    search_input.fill(asset)

    # AUDIT FIX (2026-08-15, high): this used to build the row selector from
    # the bare, unscoped asset_row selector - the exact scoping bug already
    # found and fixed in get_available_binomo_assets (asset_list_scope's own
    # comment: an unscoped "div.asset-row" search also matches hidden rows
    # from OTHER trade-mode tabs already present in the DOM, confirmed live
    # 111 unscoped rows vs 84 scoped for a list showing "Активно: 85"). This
    # function places REAL trades, so a name collision here isn't just a
    # wrong payout read - it's a Playwright strict-mode click failure
    # (silently blocking the trade) on any asset name that also exists in
    # a hidden tab.
    row_selector = (
        f"{SELECTORS['asset_list_scope']} {SELECTORS['asset_row']}"
        f":has({SELECTORS['asset_row_name']}:text-is('{asset}'))"
    )
    asset_row_probe = _safe_find(page, row_selector, description="asset_row")
    if asset_row_probe is None:
        return f"asset row not found for {asset!r}"
    if not _safe_click(page, row_selector, description="asset_row"):
        return f"could not click asset row for {asset!r}"
    _clear_price_feed_cache()
    return None


def _parse_payout_percent(text: str) -> Optional[float]:
    try:
        return float(text.strip().rstrip("%").strip())
    except (ValueError, AttributeError):
        return None


def get_available_binomo_assets(page) -> list[dict]:
    """Returns [{"name": str, "payout_percent": float}, ...] for every asset
    currently open for trading on Binomo (weekends/off-hours already
    accounted for by Binomo itself). payout_percent is the standard
    "Прибуток" payout, not the second "Для VIP" figure shown next to it.

    Reads the same '#assets-list' picker _select_asset() uses, with no
    search filter applied — confirmed live 2026-08-10 that the picker only
    renders currently-open assets (DOM row count matched the picker's own
    "Активно: N" counter exactly), scoped via asset_list_scope so other
    trade-mode tabs' hidden rows aren't accidentally included (see that
    selector's comment). The price WebSocket (wss://as.binomo.com) was also
    checked live and carries no such list — it only streams ticks for
    whatever's already subscribed, so this can't be read from there.

    Leaves the picker closed on the way out (toggles the same open button)
    so callers - notably _select_asset(), used right after this in the
    correlation-check loop - find it in the state they expect."""
    _dismiss_blocking_overlay(page)
    picker_button_probe = _safe_find(page, SELECTORS["asset_picker_open_button"], description="asset_picker_open_button")
    if picker_button_probe is None:
        return []
    if not _safe_click(page, SELECTORS["asset_picker_open_button"], description="asset_picker_open_button"):
        return []

    row_selector = f"{SELECTORS['asset_list_scope']} {SELECTORS['asset_row']}"
    try:
        page.wait_for_selector(row_selector, timeout=_DEFAULT_FIND_TIMEOUT_MS)
    except Exception:
        shot = _screenshot(page, "missing_asset_list_rows")
        logger.error(
            "Binomo executor: asset list rows not found (selector=%r). Not "
            "guessing an alternative. Screenshot: %s", row_selector, shot,
        )
        notify_admin(
            f"⚠️ Binomo executor: список активів не завантажився. "
            f"Скріншот: {shot or 'не вдалося зберегти'}",
            alert_key="binomo_missing_element_asset_list_rows",
        )
        return []

    result = []
    for row in page.query_selector_all(row_selector):
        name_el = row.query_selector(SELECTORS["asset_row_name"])
        payout_el = row.query_selector(SELECTORS["asset_row_payout"])
        if name_el is None or payout_el is None:
            continue
        name = name_el.inner_text().strip()
        payout = _parse_payout_percent(payout_el.inner_text())
        if name and payout is not None:
            result.append({"name": name, "payout_percent": payout})

    # Best-effort close — a failed close here shouldn't fail the whole read,
    # but IS worth a log line since it can break the next _select_asset call.
    reopened_button_probe = _safe_find(page, SELECTORS["asset_picker_open_button"], description="asset_picker_open_button")
    if reopened_button_probe is not None:
        if not _safe_click(page, SELECTORS["asset_picker_open_button"], description="asset_picker_close_button"):
            logger.warning("Binomo executor: could not close asset picker after reading it — next asset switch may misbehave.")

    return result


def list_available_assets() -> None:
    """Prints the currently-tradeable Binomo assets and their payout, and
    exits. Read-only — opens a session, reads the picker, closes. Run with:
        python binomo_executor.py --list-assets
    """
    from playwright.sync_api import sync_playwright

    with sync_playwright() as p:
        browser, context, page = _launch_session(p, headless=config.BINOMO_HEADLESS)

        if not _is_logged_in(page):
            logger.critical("--list-assets: not logged in. Run `python binomo_executor.py --login` first.")
            browser.close()
            return

        assets = get_available_binomo_assets(page)
        browser.close()

    print(f"Активних активів: {len(assets)}")
    for item in assets:
        print(f"  {item['name']} — {item['payout_percent']:.0f}%")


def place_binary_trade(page, asset: str, direction: str, amount: float, expiry_seconds: int) -> dict:
    """direction: 'up' | 'down'. Returns
    {"success": bool, "error": str|None, "actual_expiry_seconds": int|None}.
    actual_expiry_seconds is the real duration _set_expiry_time achieved -
    see its docstring for why this can differ from the requested
    expiry_seconds and why the caller must persist the real value, not the
    requested one. Every real click on amount/direction is preceded by an
    audit screenshot, per the task's audit-trail requirement."""
    if direction not in ("up", "down"):
        return {"success": False, "error": f"invalid direction: {direction}", "actual_expiry_seconds": None}

    select_error = _select_asset(page, asset)
    if select_error:
        return {"success": False, "error": select_error, "actual_expiry_seconds": None}

    if not _fill_amount(page, amount):
        return {"success": False, "error": "could not set amount", "actual_expiry_seconds": None}

    _screenshot(page, f"before_amount_{asset}_{direction}")

    actual_expiry_seconds = _set_expiry_time(page, expiry_seconds)
    if actual_expiry_seconds is None:
        return {"success": False, "error": "could not set expiry time", "actual_expiry_seconds": None}

    direction_selector = SELECTORS["up_button"] if direction == "up" else SELECTORS["down_button"]
    direction_button_probe = _safe_find(page, direction_selector, description=f"{direction}_button")
    if direction_button_probe is None:
        return {"success": False, "error": f"{direction}_button not found", "actual_expiry_seconds": None}

    _screenshot(page, f"before_click_{asset}_{direction}")
    if not _safe_click(page, direction_selector, description=f"{direction}_button"):
        return {"success": False, "error": f"could not click {direction}_button", "actual_expiry_seconds": None}

    # DIAGNOSTIC (2026-08-19): 'trade_confirmation_toast' (selector
    # 'way-toast, .toast') started missing on every real trade today
    # (2/2) - confirmed live via db.BinomoTrade that both trades placed
    # and resolved fine regardless (this check is best-effort, never
    # blocks placement), so it's not a functional problem, but it IS
    # worth understanding whether Binomo's toast markup genuinely
    # changed. A toast that auto-dismisses in a couple seconds is
    # already gone by the time _safe_find's own 5s-timeout failure
    # screenshot fires. This grabs one immediately after the click,
    # before the toast has had time to disappear, purely to SEE the
    # current markup - per the "не гадати" policy, the selector below
    # is not touched until there's a live screenshot to base a real fix
    # on. Remove this extra screenshot once that's resolved either way.
    try:
        page.wait_for_timeout(300)
    except Exception:
        pass
    _screenshot(page, f"toast_diagnostic_{asset}_{direction}")

    confirmation = _safe_find(
        page, SELECTORS["trade_confirmation_toast"], description="trade_confirmation_toast", timeout_ms=5000
    )
    if confirmation is None:
        # Not necessarily a failure — some UIs skip a toast — but we can't
        # positively confirm the trade went through either. Log loudly.
        logger.warning("Binomo executor: no confirmation toast seen after clicking %s on %s", direction, asset)

    return {"success": True, "error": None, "actual_expiry_seconds": actual_expiry_seconds}


_SETTLED_TIMESTAMP_RE = re.compile(r"\d{2}:\d{2}:\d{2}\s*·")
_CURRENCY_AMOUNT_RE = re.compile(r"[+-]?\s*[\d\s]+,\d{2}\s*₴")
_SETTLED_ROW_TIME_RE = re.compile(r"(\d{2}):(\d{2}):(\d{2})\s*·\s*(\d{1,2})\s*([а-яіїєґА-ЯІЇЄҐ]+)")
# Standard 3-letter Ukrainian month abbreviations, as shown in Binomo's own
# settled-row timestamps (e.g. "10 сер" = 10 серпня = August 10 - confirmed
# live 2026-08-12, matching that day's real date).
_UK_MONTH_ABBR = {
    "січ": 1, "лют": 2, "бер": 3, "кві": 4, "тра": 5, "чер": 6,
    "лип": 7, "сер": 8, "вер": 9, "жов": 10, "лис": 11, "гру": 12,
}
# How close a settled row's displayed entry time must be to our own
# entry_ts to count as the SAME trade. Wide enough to absorb a little
# clock skew / display rounding, narrow enough that two of our own trades
# on the same asset (which in practice land minutes apart - our closest
# same-day pair, 2026-08-12, were ~6 minutes apart) can never be confused.
_TRADE_HISTORY_MATCH_TOLERANCE_SECONDS = 60


def _parse_settled_row_timestamp(text: str, *, reference: datetime) -> Optional[datetime]:
    """Parses a settled deal row's "HH:MM:SS · D мон" into a naive UTC
    datetime comparable to our own entry_ts. Binomo displays in GMT+3
    (confirmed live via the page's own clock label) and never shows a
    year, so `reference` (the trade's own entry_ts) supplies it, handling
    the one edge case where that's ambiguous: a trade that entered in
    December being read back in January, or vice versa."""
    m = _SETTLED_ROW_TIME_RE.search(text)
    if not m:
        return None
    hour, minute, second, day, month_abbr = m.groups()
    month = _UK_MONTH_ABBR.get(month_abbr.lower()[:3])
    if month is None:
        return None
    year = reference.year
    if month == 12 and reference.month == 1:
        year -= 1
    elif month == 1 and reference.month == 12:
        year += 1
    try:
        local_dt = datetime(year, month, int(day), int(hour), int(minute), int(second))
    except ValueError:
        return None
    return local_dt - timedelta(hours=3)  # Binomo's GMT+3 display -> UTC


