#!/usr/bin/env python
# binomo_executor.py
"""Part 3: executes binary-option trades on Binomo (binomo.com) for signals
generated by the existing cTrader-based pipeline (analysis.py / scanner.py),
via Playwright browser automation — Binomo has no public trading API.

ARCHITECTURE: this is a SEPARATE, STANDALONE LOCAL PROCESS. It is NOT part
of app.py's Twisted reactor / Flask app, is NOT deployed to Fly.io, and is
NOT imported by any cloud-side module (api.py, telegram_ui.py, bot.py never
import this file — Playwright isn't even in requirements.txt, only in
requirements-executor.txt, specifically so importing this module can never
happen by accident in the cloud process and crash it).

Why local instead of Fly.io: a persistent logged-in browser session
benefits from a stable IP and machine fingerprint; running it on a
shared/rotating cloud IP is both a worse fit for Binomo's anti-automation
checks and a bigger detection/ban risk for your account. Run this on your
own machine, pointed at the cloud instance's signal stream.

CROSS-PROCESS CONTROL: since this runs separately from the Telegram bot,
/binomo_status, /binomo_on and /binomo_off (telegram_ui.py, cloud process)
don't touch any in-memory flag here directly — they read/write shared flags
in the database (db.get_binomo_runtime_state / set_binomo_runtime_enabled /
trip_binomo_kill_switch), which this process polls. Same DATABASE_URL must
be reachable from both sides.

SAFETY MODEL (see config.py):
  - BINOMO_EXECUTOR_ENABLED=false by default (local .env). Nothing runs
    without this AND the DB-side runtime_enabled flag AND no tripped kill
    switch — see is_active().
  - BINOMO_ACCOUNT_MODE (demo|live) has NO remote/Telegram toggle anywhere.
    Switching to live is a manual local .env edit only.
  - BINOMO_STAKE_PERCENT is a fixed % of balance. There is no martingale/
    progression anywhere in this file, on purpose — do not add one.
  - Kill switches: BINOMO_MAX_TRADES_PER_DAY, BINOMO_MAX_CONSECUTIVE_LOSSES,
    BINOMO_MAX_DAILY_LOSS_PERCENT. Any of these trips a DB-persisted flag
    that stops new trades until an admin explicitly runs /binomo_on.

SELECTORS — verified 2026-08-09 against the live Binomo trading terminal
(Angular app) via a logged-in session, read-only DOM inspection only (no
amount/direction/confirm clicks were ever made during verification). Most
selectors use Binomo's own stable `id="qa_*"` QA hooks. Two known gaps
remain, both documented at their point of use instead of being guessed:
  - `asset_price_display` does not exist — Binomo renders the live price
    only inside a `<canvas>` chart, with no DOM/SVG/aria text node anywhere
    on the page. `_read_binomo_price()` always returns None until this is
    solved a different way (e.g. intercepting Binomo's price WebSocket).
  - `login_email_input`/`login_password_input`/`login_submit_button` are
    still unverified best-effort guesses (the login page 404s/redirects
    while already logged in, so it couldn't be inspected without logging
    the account out). This only affects the optional autofill convenience
    in `--login`; on failure it already logs a warning and lets you fill
    the form yourself, so it fails safe either way.
Nothing here guesses or falls back to a structural selector if the intended
one is missing — see _safe_find().
"""
