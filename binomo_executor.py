logger = logging.getLogger("binomo_executor")

BINOMO_BASE_URL = "https://binomo.com"
BINOMO_TRADE_URL = "https://binomo.com/trading"

SCREENSHOT_DIR = Path("logs") / "binomo_screenshots"

