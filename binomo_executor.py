# Playwright session
# ----------------------------------------------------------------------


def _storage_state_path() -> Path:
    path = Path(config.BINOMO_STORAGE_STATE_PATH)
    return path if path.is_absolute() else config.BASE_DIR / path


def login_and_save_session() -> None:
    """One-time (or as-needed) manual login helper: opens a VISIBLE browser,
    lets you log in yourself (including any CAPTCHA/2FA), then saves the
    session to BINOMO_STORAGE_STATE_PATH. Run with:
        python binomo_executor.py --login
    """
    from playwright.sync_api import sync_playwright

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=False)
        context = browser.new_context()
        page = context.new_page()
        page.goto(BINOMO_BASE_URL)

        print(
            "\nA browser window has opened. Log into your Binomo account "
            "manually (solve any CAPTCHA/2FA yourself — this tool never "
            "attempts that). Once you're logged in and can see your "
            "balance, come back here and press Enter.\n"
        )
        input("Press Enter once logged in... ")

        state_path = _storage_state_path()
        state_path.parent.mkdir(parents=True, exist_ok=True)
        context.storage_state(path=str(state_path))
        print(f"Session saved to {state_path}. You can close the browser now.")
        browser.close()


def _launch_session(playwright, *, headless: bool):
    state_path = _storage_state_path()
    if not state_path.exists():
        raise RuntimeError(
            f"No saved Binomo session at {state_path}. Run "
            "`python binomo_executor.py --login` first."
        )

    browser = playwright.chromium.launch(headless=headless)
    context = browser.new_context(storage_state=str(state_path))
    page = context.new_page()
    page.goto(BINOMO_TRADE_URL)
    return browser, context, page


def _is_logged_in(page) -> bool:
    try:
        page.wait_for_selector(SELECTORS["login_indicator"], timeout=_DEFAULT_FIND_TIMEOUT_MS)
        return True
    except Exception:
        return False


# ----------------------------------------------------------------------
# Safe DOM interaction — never guesses an alternate selector. On timeout:
# screenshot, log, return None. Callers must treat None as "stop, don't
# trade", per the task's own explicit rule.
# ----------------------------------------------------------------------


def _screenshot(page, tag: str) -> Optional[str]:
    try:
        SCREENSHOT_DIR.mkdir(parents=True, exist_ok=True)
        ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
        path = SCREENSHOT_DIR / f"{ts}_{tag}.png"
        page.screenshot(path=str(path))
        return str(path)
    except Exception:
        logger.exception("Could not save audit screenshot for %s", tag)
        return None


def _safe_find(page, selector: str, *, description: str, timeout_ms: int = _DEFAULT_FIND_TIMEOUT_MS):
    try:
        return page.wait_for_selector(selector, timeout=timeout_ms)
    except Exception:
        shot = _screenshot(page, f"missing_{description}")
        logger.error(
            "Binomo executor: element not found for '%s' (selector=%r). "
            "Not guessing an alternative — stopping this action. Screenshot: %s",
            description, selector, shot,
        )
        notify_admin(
            f"⚠️ Binomo executor: елемент \"{description}\" не знайдено на сторінці. "
            "Потрібна ручна перевірка (можливо, змінився дизайн сайту). "
            f"Скріншот: {shot or 'не вдалося зберегти'}",
        )
        return None


# ----------------------------------------------------------------------
# Balance
# ----------------------------------------------------------------------


def get_account_balance(page) -> Optional[float]:
    el = _safe_find(page, SELECTORS["balance_amount"], description="balance_amount")
    if el is None:
        return None

    try:
        text = el.inner_text().strip()
        cleaned = "".join(ch for ch in text if ch.isdigit() or ch in ".,").replace(",", "")
        return float(cleaned) if cleaned else None
    except Exception:
        logger.exception("Could not parse Binomo balance text")
        return None


